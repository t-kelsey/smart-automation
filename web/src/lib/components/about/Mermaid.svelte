<!--
@component
Renders a Mermaid diagram on the client. Mermaid is loaded lazily, so it adds nothing to the initial bundle.

@param code - Mermaid diagram source.
@param [label] - Accessible description of the diagram.
-->

<script lang="ts">
	import { onMount } from 'svelte';

	interface Props {
		code: string;
		label?: string;
	}

	let { code, label = 'Diagram' }: Props = $props();

	let svg = $state('');
	let failed = $state(false);

	onMount(async () => {
		try {
			const { default: mermaid } = await import('mermaid');
			const dark = matchMedia('(prefers-color-scheme: dark)').matches;
			mermaid.initialize({
				startOnLoad: false,
				theme: dark ? 'dark' : 'default',
				securityLevel: 'strict'
			});
			const id = `mermaid-${Math.random().toString(36).slice(2)}`;
			({ svg } = await mermaid.render(id, code));
		} catch {
			failed = true;
		}
	});
</script>

<figure class="overflow-x-auto" aria-label={label}>
	{#if svg}
		<!-- eslint-disable-next-line svelte/no-at-html-tags -- SVG generated by mermaid from our own static source -->
		<div class="flex justify-center [&_svg]:h-auto [&_svg]:max-w-full">{@html svg}</div>
	{:else if failed}
		<pre class="text-sm whitespace-pre-wrap">{code}</pre>
	{:else}
		<div class="h-40 animate-pulse rounded-container preset-tonal-surface"></div>
	{/if}
</figure>
